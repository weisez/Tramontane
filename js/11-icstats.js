let STATS_SEL = null;
function statsPool() {
  const m = S.meta, seen = new Set(), out = [];
  [...(m.statsOwn ? [] : icLive()), ...(m.stats || []), ...(m.statsOwn ? [] : IC_STATS)].forEach((s) => {
    if (!s || !s.l || s.n == null || s.n === "") return;
    const k = String(s.l).trim().toLowerCase(); if (seen.has(k)) return; seen.add(k); out.push(s);
  });
  return out;
}
